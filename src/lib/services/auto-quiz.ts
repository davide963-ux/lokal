import { db } from "@/lib/db";
import { DomainError } from "@/lib/errors";
import { generateQuestions, MIN_GENERATED_QUESTIONS, type GeneratedQuestion, type GeneratorPools } from "@/lib/quiz/generator";
import { buildDishSnapshot } from "./dish-snapshot";
import { notifyAdmins } from "./notifications";
import { publishQuiz, unpublishQuiz } from "./quizzes";

/** Distractor material: the restaurant's own vocabulary and its other dishes. */
async function loadPools(dishId: string): Promise<GeneratorPools> {
  const [ingredients, allergens, dishes, categories] = await Promise.all([
    db.ingredient.findMany({ select: { name: true }, orderBy: { name: "asc" } }),
    db.allergen.findMany({ select: { name: true }, orderBy: [{ sortOrder: "asc" }, { name: "asc" }] }),
    db.dish.findMany({
      where: { id: { not: dishId }, status: { not: "ARCHIVED" } },
      select: { cookingMethod: true, garnishes: true, servingTemperature: true },
      orderBy: { id: "asc" }, // stable order → deterministic output
    }),
    db.category.findMany({ select: { name: true }, orderBy: { name: "asc" } }),
  ]);
  const vals = (k: "cookingMethod" | "garnishes" | "servingTemperature") => dishes.map((d) => d[k]).filter((v): v is string => !!v?.trim());
  return {
    ingredientNames: ingredients.map((i) => i.name),
    allergenNames: allergens.map((a) => a.name),
    cookingMethods: vals("cookingMethod"),
    garnishes: vals("garnishes"),
    servingTemperatures: vals("servingTemperature"),
    categoryNames: categories.map((c) => c.name),
  };
}

/** Questions for a dish from its CURRENT recorded data. Seeded by the dish id, so unchanged data → identical questions. */
export async function generateForDish(dishId: string) {
  const [snapshot, pools] = await Promise.all([buildDishSnapshot(db, dishId), loadPools(dishId)]);
  return { dishName: snapshot.name, questions: generateQuestions(snapshot, pools, dishId) };
}

const optionsOf = (q: GeneratedQuestion) =>
  q.questionType === "TRUE_FALSE"
    ? [{ text: "True", isCorrect: q.trueFalseAnswer === true }, { text: "False", isCorrect: q.trueFalseAnswer === false }]
    : q.options;

const signature = (qs: { text: string; type: string; explanation: string | null; options: { text: string; isCorrect: boolean }[] }[]) =>
  JSON.stringify(qs.map((q) => [q.text, q.type, q.explanation ?? "", q.options.map((o) => [o.text, o.isCorrect])]));

/**
 * Creates the dish's quiz if missing and (re)writes its questions. Returns whether anything changed.
 * Identical content is not rewritten, so republishing never produces a pointless new quiz revision.
 */
async function writeGenerated(dishId: string, dishName: string, questions: GeneratedQuestion[]) {
  return db.$transaction(async (tx) => {
    // createMany + skipDuplicates (INSERT ... ON CONFLICT DO NOTHING): two parallel syncs can't collide on the unique dishId.
    const made = await tx.quiz.createMany({
      data: [{ dishId, title: `${dishName} quiz`, autoGenerated: true, passingScore: 80, allowRetries: true, randomizeAnswers: true, showCorrectAnswers: true }],
      skipDuplicates: true,
    });
    const created = made.count === 1;
    const quiz = await tx.quiz.findFirstOrThrow({
      where: { dishId },
      include: { questions: { orderBy: [{ sortOrder: "asc" }, { id: "asc" }], include: { options: { orderBy: [{ sortOrder: "asc" }, { id: "asc" }] } } } },
    });
    const next = signature(questions.map((q) => ({ text: q.questionText, type: q.questionType, explanation: q.explanation, options: optionsOf(q) })));
    const current = signature(quiz.questions.map((q) => ({ text: q.questionText, type: q.questionType, explanation: q.explanation, options: q.options.map((o) => ({ text: o.answerText, isCorrect: o.isCorrect })) })));
    if (!created && quiz.autoGenerated && next === current) return { quizId: quiz.id, created, changed: false, status: quiz.status };

    await tx.quizQuestion.deleteMany({ where: { quizId: quiz.id } });
    for (const [i, q] of questions.entries()) {
      await tx.quizQuestion.create({
        data: {
          quizId: quiz.id, questionText: q.questionText, questionType: q.questionType, explanation: q.explanation, sortOrder: i,
          options: { create: optionsOf(q).map((o, j) => ({ answerText: o.text, isCorrect: o.isCorrect, sortOrder: j })) },
        },
      });
    }
    await tx.quiz.update({ where: { id: quiz.id }, data: { autoGenerated: true } });
    return { quizId: quiz.id, created, changed: true, status: quiz.status };
  });
}

export type SyncOutcome =
  | { action: "skipped" | "insufficient" | "unchanged" | "manual-review" | "unpublished" }
  | { action: "generated" | "updated"; questions: number };

/**
 * Keeps a published dish's quiz in step with the dish. Called after a dish is first published and whenever a
 * published dish gets a new version.
 *  - no quiz yet            → generate one and publish it (employees are notified by publishQuiz)
 *  - auto-generated quiz    → regenerate so no question can contradict the new recipe; publish a new quiz revision only if the content changed
 *  - manager-edited quiz    → never touched; the manager is asked to review it
 */
export async function syncQuizWithDish(dishId: string): Promise<SyncOutcome> {
  const dish = await db.dish.findUnique({ where: { id: dishId }, select: { id: true, name: true, status: true } });
  if (!dish || dish.status !== "PUBLISHED") return { action: "skipped" };
  const link = `/admin/quizzes/${dishId}`;
  const quiz = await db.quiz.findUnique({ where: { dishId }, select: { id: true, status: true, autoGenerated: true } });

  if (quiz && !quiz.autoGenerated) {
    await notifyAdmins({ type: "QUIZ_NEEDS_REVIEW", title: `${dish.name} changed: check its quiz`, message: "The dish was updated and its quiz is hand-edited, so it was left as is. Make sure the questions are still correct.", link });
    return { action: "manual-review" };
  }

  const { questions } = await generateForDish(dishId);
  if (questions.length < MIN_GENERATED_QUESTIONS) {
    if (quiz?.status === "PUBLISHED") {
      // The recipe no longer supports a quiz, and the old questions may now be wrong: take it offline rather than leave stale ones live.
      await unpublishQuiz(quiz.id);
      await notifyAdmins({ type: "QUIZ_NEEDS_REVIEW", title: `${dish.name}: quiz taken offline`, message: "After the update there isn't enough information to generate a reliable quiz. Add ingredients, allergens or preparation details, or write questions yourself.", link });
      return { action: "unpublished" };
    }
    return { action: "insufficient" };
  }

  const w = await writeGenerated(dishId, dish.name, questions);
  if (!w.changed) return { action: "unchanged" };
  // Publish brand-new quizzes and ones already live; a quiz the manager deliberately left in draft stays a draft.
  if (w.created || w.status === "PUBLISHED") await publishQuiz(w.quizId);
  if (w.created) {
    await notifyAdmins({ type: "QUIZ_NEEDS_REVIEW", title: `Quiz generated: ${dish.name}`, message: `${questions.length} questions were created from the recipe data and are live. Have a quick look.`, link });
  }
  return { action: w.created ? "generated" : "updated", questions: questions.length };
}

/** Fire-and-forget wrapper for dish saves: a quiz problem must never fail or roll back the manager's save. */
export async function syncQuizSafely(dishId: string) {
  try {
    return await syncQuizWithDish(dishId);
  } catch (err) {
    console.error("[auto-quiz] sync failed for dish", dishId, err);
    return { action: "skipped" } as SyncOutcome;
  }
}

/** The manager's "Generate / regenerate from dish" button. Works on drafts too; replaces all questions. */
export async function generateQuizNow(dishId: string) {
  const dish = await db.dish.findUnique({ where: { id: dishId }, select: { name: true, status: true } });
  if (!dish) throw new DomainError("Dish not found.");
  const { questions } = await generateForDish(dishId);
  if (questions.length < MIN_GENERATED_QUESTIONS) {
    throw new DomainError("There isn't enough information on this dish to generate a reliable quiz. Add its ingredients, allergens, cooking method or preparation time first.");
  }
  const w = await writeGenerated(dishId, dish.name, questions);
  const live = dish.status === "PUBLISHED" && w.status === "PUBLISHED" && !w.created;
  if (live && w.changed) await publishQuiz(w.quizId);
  return { questions: questions.length, changed: w.changed, published: live };
}
