import { beforeEach, describe, expect, it, vi } from "vitest";
import { db } from "@/lib/db";
import { createDish, publishDish, updateDish } from "@/lib/services/dishes";
import { generateQuizNow, syncQuizWithDish } from "@/lib/services/auto-quiz";
import { saveQuestion, publishQuiz } from "@/lib/services/quizzes";
import { createIngredient } from "@/lib/services/catalog";
import { getEmployeeDashboard } from "@/lib/services/training";
import { makeCategory, makeUser, resetDb, takeQuiz } from "./helpers";

let adminId: string, empId: string, pastaId: string;
let eggs: string, gluten: string, milk: string;

type Input = Parameters<typeof createDish>[1];
const rich = (over: Partial<Input> = {}): Input => ({
  name: "Spaghetti Carbonara", categoryId: pastaId, allergensVerified: true,
  ingredients: [{ name: "Spaghetti" }, { name: "Guanciale", quantity: "80 g" }, { name: "Egg yolk" }, { name: "Pecorino Romano", isOptional: true }],
  allergens: [{ allergenId: eggs, presence: "CONTAINS" }, { allergenId: gluten, presence: "CONTAINS" }, { allergenId: milk, presence: "MAY_CONTAIN" }],
  dietaryTags: ["Halal"], cookingMethod: "Pan-fried", prepTimeMinutes: 12, servingTemperature: "Hot", garnishes: "Black pepper", ...over,
});

beforeEach(async () => {
  await resetDb();
  adminId = (await makeUser({ role: "ADMIN" })).id;
  empId = (await makeUser({ name: "Marco" })).id;
  pastaId = (await makeCategory("Pasta")).id;
  await makeCategory("Desserts"); await makeCategory("Salads"); await makeCategory("Drinks");
  const al = async (name: string) => (await db.allergen.create({ data: { name } })).id;
  eggs = await al("Eggs"); gluten = await al("Cereals containing gluten"); milk = await al("Milk");
  for (const n of ["Fish", "Peanuts", "Sesame", "Soybeans", "Celery"]) await al(n);
  for (const n of ["Tomato", "Basil", "Mozzarella", "Chicken", "Cream", "Prawns", "Lemon"]) await createIngredient({ name: n });
  // another dish provides realistic wrong options for cooking method / garnish / serving temperature
  const other = await createDish(adminId, { name: "Tiramisu", categoryId: pastaId, allergensVerified: true, cookingMethod: "No-bake", garnishes: "Cocoa powder", servingTemperature: "Chilled" });
  await db.dish.update({ where: { id: other.id }, data: { cookingMethod: "No-bake" } });
  for (const [n, c, g] of [["Margherita", "Wood-fired", "Fresh basil"], ["Caesar", "Grilled", "Parmesan shavings"], ["Soup", "Simmered", "Parsley"]] as const) {
    await createDish(adminId, { name: n, categoryId: pastaId, allergensVerified: true, cookingMethod: c, garnishes: g, servingTemperature: "Warm" });
  }
});

const quizOf = (dishId: string) => db.quiz.findUnique({ where: { dishId }, include: { questions: { include: { options: true }, orderBy: { sortOrder: "asc" } } } });

describe("automatic quiz on a new dish", () => {
  it("publishing a documented dish creates, publishes and announces a quiz with no manager effort", async () => {
    const { id } = await createDish(adminId, rich());
    expect(await quizOf(id)).toBeNull(); // a draft has no quiz yet
    await publishDish(adminId, id);
    const quiz = (await quizOf(id))!;
    expect(quiz).toMatchObject({ status: "PUBLISHED", autoGenerated: true, passingScore: 80, allowRetries: true, currentVersion: 1 });
    expect(quiz.questions.length).toBeGreaterThanOrEqual(3);
    for (const q of quiz.questions) {
      if (q.questionType === "MULTIPLE_CHOICE") expect(q.options.filter((o) => o.isCorrect)).toHaveLength(1);
    }
    expect(await db.quizRevision.count({ where: { quizId: quiz.id } })).toBe(1);
    expect(await db.notification.count({ where: { userId: empId, type: "QUIZ_AVAILABLE" } })).toBe(1);
    expect(await db.notification.count({ where: { userId: adminId, type: "QUIZ_NEEDS_REVIEW", title: { startsWith: "Quiz generated" } } })).toBe(1);
  });
  it("an employee can study the dish and take the generated quiz straight away", async () => {
    const { id } = await createDish(adminId, rich());
    await publishDish(adminId, id);
    const target = (await getEmployeeDashboard(empId)).dishes.find((d) => d.id === id)!;
    expect(target.status.quizState).toBe("LOCKED"); // quiz exists, locked until studied
    expect(await takeQuiz(empId, id)).toMatchObject({ score: 100, passed: true });
  });
  it("a sparsely documented dish gets no quiz and no noise", async () => {
    const { id } = await createDish(adminId, { name: "Water", categoryId: pastaId, allergensVerified: true });
    await db.notification.deleteMany();
    await publishDish(adminId, id);
    expect(await quizOf(id)).toBeNull();
    expect(await db.notification.count({ where: { userId: adminId } })).toBe(0);
  });
  it("a draft or archived dish is never synced", async () => {
    const { id } = await createDish(adminId, rich());
    expect(await syncQuizWithDish(id)).toEqual({ action: "skipped" });
    expect(await quizOf(id)).toBeNull();
  });
});

describe("keeping generated quizzes correct as the dish changes", () => {
  it("removing an ingredient regenerates the quiz so no question refers to it; the old attempt keeps its original version", async () => {
    const { id } = await createDish(adminId, rich());
    await publishDish(adminId, id);
    const first = await takeQuiz(empId, id);
    const q1 = (await quizOf(id))!;
    await updateDish(adminId, id, rich({ ingredients: [{ name: "Spaghetti" }, { name: "Pecorino Romano" }, { name: "Black pepper" }, { name: "Lemon" }] }));
    const q2 = (await quizOf(id))!;
    expect(q2.currentVersion).toBe(2);
    expect(await db.quizRevision.count({ where: { quizId: q2.id } })).toBe(2);
    expect(q2.status).toBe("PUBLISHED");
    const everywhere = q2.questions.flatMap((q) => [q.questionText, q.explanation ?? "", ...q.options.map((o) => `${o.answerText}:${o.isCorrect}`)]).join("\n");
    expect(everywhere).not.toMatch(/Guanciale:true/);
    expect(everywhere).not.toMatch(/Egg yolk:true/);
    expect(q2.questions.map((q) => q.id)).not.toEqual(q1.questions.map((q) => q.id));
    // history: the first attempt still points at revision 1 with its original question count
    const old = await db.quizAttempt.findUniqueOrThrow({ where: { id: first.attemptId }, include: { quizRevision: true } });
    expect(old.quizRevision.version).toBe(1);
  });
  it("saving a change that doesn't affect any question creates no new quiz revision", async () => {
    const { id } = await createDish(adminId, rich());
    await publishDish(adminId, id);
    await updateDish(adminId, id, rich({ managerNotes: "Staff meal on Fridays" }));
    expect(await db.dishRevision.count({ where: { dishId: id } })).toBe(2);
    const quiz = (await quizOf(id))!;
    expect(quiz.currentVersion).toBe(1);
    expect(await db.quizRevision.count({ where: { quizId: quiz.id } })).toBe(1);
  });
  it("a hand-edited quiz is never overwritten: the manager is asked to review instead", async () => {
    const { id } = await createDish(adminId, rich());
    await publishDish(adminId, id);
    const quiz = (await quizOf(id))!;
    await saveQuestion(quiz.id, null, { questionText: "My own question?", questionType: "TRUE_FALSE", trueFalseAnswer: true });
    expect((await quizOf(id))!.autoGenerated).toBe(false);
    const before = JSON.stringify((await quizOf(id))!.questions.map((q) => [q.questionText, q.options.map((o) => [o.answerText, o.isCorrect])]));
    await db.notification.deleteMany();
    await updateDish(adminId, id, rich({ cookingMethod: "Baked" }));
    expect(JSON.stringify((await quizOf(id))!.questions.map((q) => [q.questionText, q.options.map((o) => [o.answerText, o.isCorrect])]))).toBe(before);
    expect(await db.notification.count({ where: { userId: adminId, type: "QUIZ_NEEDS_REVIEW", title: { contains: "check its quiz" } } })).toBe(1);
  });
  it("if an update leaves too little data, the stale generated quiz is taken offline and the manager told", async () => {
    const { id } = await createDish(adminId, rich());
    await publishDish(adminId, id);
    await updateDish(adminId, id, { name: "Spaghetti Carbonara", categoryId: pastaId, allergensVerified: true });
    expect((await quizOf(id))!.status).toBe("DRAFT");
    expect(await db.notification.count({ where: { userId: adminId, title: { contains: "quiz taken offline" } } })).toBe(1);
    await expect(takeQuiz(empId, id)).rejects.toThrow(/not available/);
  });
  it("a retraining update regenerates the quiz and still requires re-study", async () => {
    const { id } = await createDish(adminId, rich());
    await publishDish(adminId, id);
    await takeQuiz(empId, id);
    await updateDish(adminId, id, rich({ cookingMethod: "Baked", requiresRetraining: true }));
    const status = (await getEmployeeDashboard(empId)).dishes.find((d) => d.id === id)!.status;
    expect(status).toMatchObject({ studyState: "NEEDS_REVIEW", quizState: "LOCKED" });
    expect(await takeQuiz(empId, id)).toMatchObject({ passed: true });
  });
  it("two syncs at once leave exactly one quiz", async () => {
    const { id } = await createDish(adminId, rich());
    await publishDish(adminId, id);
    await db.quiz.deleteMany();
    await Promise.all([syncQuizWithDish(id), syncQuizWithDish(id), syncQuizWithDish(id)]);
    expect(await db.quiz.count()).toBe(1);
    expect((await quizOf(id))!.questions.length).toBeGreaterThanOrEqual(3);
  });
  it("a failure in quiz generation never fails or rolls back publishing the dish", async () => {
    const { id } = await createDish(adminId, rich());
    const quizzes = await import("@/lib/services/quizzes");
    const boom = vi.spyOn(quizzes, "publishQuiz").mockRejectedValueOnce(new Error("boom"));
    const logged = vi.spyOn(console, "error").mockImplementation(() => {});
    try {
      await expect(publishDish(adminId, id)).resolves.toBeTruthy();
      expect(boom).toHaveBeenCalledTimes(1); // the failure really happened…
      expect(logged).toHaveBeenCalledWith(expect.stringContaining("[auto-quiz]"), id, expect.any(Error)); // …was logged…
    } finally {
      boom.mockRestore(); logged.mockRestore();
    }
    expect((await db.dish.findUniqueOrThrow({ where: { id } })).status).toBe("PUBLISHED"); // …and publishing stood
    expect(await db.dishRevision.count({ where: { dishId: id } })).toBe(1);
    expect((await quizOf(id))!.status).toBe("DRAFT"); // quiz exists but wasn't published; a later dish save or the button fixes it
  });
});

describe("manager's generate / regenerate button", () => {
  it("builds a draft quiz for an unpublished dish without publishing anything", async () => {
    const { id } = await createDish(adminId, rich());
    const r = await generateQuizNow(id);
    expect(r).toMatchObject({ changed: true, published: false });
    expect((await quizOf(id))).toMatchObject({ status: "DRAFT", autoGenerated: true });
  });
  it("replaces hand-written questions with generated ones and returns the quiz to auto-sync", async () => {
    const { id } = await createDish(adminId, rich());
    await publishDish(adminId, id);
    const quiz = (await quizOf(id))!;
    await saveQuestion(quiz.id, null, { questionText: "Custom?", questionType: "TRUE_FALSE", trueFalseAnswer: false });
    expect((await quizOf(id))!.autoGenerated).toBe(false);
    const r = await generateQuizNow(id);
    expect(r).toMatchObject({ changed: true, published: true });
    const after = (await quizOf(id))!;
    expect(after.autoGenerated).toBe(true);
    expect(after.questions.some((q) => q.questionText === "Custom?")).toBe(false);
    expect(after.currentVersion).toBe(2);
  });
  it("is a no-op on identical content, and refuses (changing nothing) when the dish lacks data", async () => {
    const { id } = await createDish(adminId, rich());
    await publishDish(adminId, id);
    expect((await generateQuizNow(id)).changed).toBe(false);
    const bare = await createDish(adminId, { name: "Plain", categoryId: pastaId });
    await expect(generateQuizNow(bare.id)).rejects.toThrow(/isn't enough information/);
    expect(await quizOf(bare.id)).toBeNull();
    await publishQuiz((await quizOf(id))!.id); // existing quiz unaffected
  });
});
